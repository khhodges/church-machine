"""Resolve latest saved sources and compile a private, coherent development graph.

Never publish revisions or rewrite the selected saved Namespace. Historical
replays do not call this module. Missing/broken newest inputs never fall back.
"""
import copy
import hashlib
import json
from pathlib import Path
import struct
from contextlib import contextmanager
from tempfile import TemporaryDirectory

from server.lump_approvals import write_approvals
from server.lump_integrity import compute_number


@contextmanager
def latest_build(backend, document, directory):
    manifest_path = Path(directory) / "manifest.json"
    manifest_bytes = manifest_path.read_bytes()
    manifest = json.loads(manifest_bytes)
    from server.compact_rebuild import compiler_fingerprint
    compiler = compiler_fingerprint()
    resolved = copy.deepcopy(document)
    evidence, approvals = [], {}
    with TemporaryDirectory(prefix="development-latest-") as temporary:
        root = Path(temporary)
        for row in resolved["rows"]:
            name = row["name"]
            if row["kind"] != "lump":
                if row.get("selection"):
                    raise ValueError(f"NS[{row['slot']}] {name}: this {row['kind']} has an explicit compiled "
                                     "artifact which the native generator cannot consume. Nothing was substituted or sent.")
                # Namespace and Thread bodies are generated by stage() on every
                # build from this configuration, not historical binary snapshots.
                evidence.append(dict(slot=row["slot"], name=name, kind=row["kind"],
                                     origin="current-definition", definition=copy.deepcopy(row)))
                continue
            try:
                candidates = [r for r in manifest if r.get("abstraction") == name]
                if not candidates:
                    raise ValueError("No latest compilation exists")
                newest = max(int(r.get("lump_version") or 0) for r in candidates)
                newest_rows = [r for r in candidates if int(r.get("lump_version") or 0) == newest]
                row_info, inspected = backend._latest_primary_compilation(
                    name, include_system_managed=True)
                # The existing inspector rejects bad signatures, source and bytes.
                # Never let its candidate filtering silently select an older row.
                if (int(row_info.get("lump_version") or 0) != newest or
                        len({r.get("filename") for r in newest_rows}) != 1):
                    raise ValueError("Newest compilation is invalid or ambiguous; no older revision was used")
                source = inspected.get("editing_source", inspected.get("source"))
                if not isinstance(source, str):
                    raise ValueError("Latest compilation has no verified source")
                language = row_info.get("language") or "assembly"
                with backend.app.app_context():
                    response = backend.app.make_response(backend._compile_development_source(
                        dict(source=source, language=language, tier=2)))
                compiled = response.get_json()
                if response.status_code != 200 or not compiled or not compiled.get("ok"):
                    raise ValueError((compiled or {}).get("error") or str((compiled or {}).get("errors")))
                if compiled.get("abstractionName") != name:
                    raise ValueError("Latest source compiles to a different abstraction")
                words = compiled["words"]
                raw = struct.pack(f">{len(words)}I", *words)
                sha = hashlib.sha256(raw).hexdigest()
                token = compute_number(name, raw)
                filename = f"{name}.1.{token}.lump"
                (root / filename).write_bytes(raw)
                approval = {key: compiled[key] for key in (
                    "trust_origin", "compiler_identity", "compiler_version",
                    "compiler_record", "portable_binding") if key in compiled}
                # Match the normal Save LUMP path for compiler-owned SELF:
                # retain the unresolved marker and authenticated declarations.
                if (not approval.get("portable_binding") and words[0] & 255 == 1
                        and words[-1] in (0, 0xFEED5E1F)
                        and len(compiled.get("capabilities", [])) == 1
                        and compiled["capabilities"][0].get("compiler_owned_self")):
                    from server.portable_binding import validate_portable_binding
                    approval["portable_binding"] = validate_portable_binding(dict(
                        schema="church.portable-lump-binding/v1", owner=f"{name}#1",
                        dependencies=compiled["capabilities"]), 1)
                approval.update(binary_hash=sha, dot_name=name, issue_n=1,
                                abstraction=name, filename=filename)
                approvals[sha] = approval
                row["selection"] = dict(filename=filename, binaryHash=sha,
                                        token=token, revision=newest)
                evidence.append(dict(slot=row["slot"], name=name, kind=row["kind"],
                    origin="latest-source-current-compiler", revision=newest,
                    sourceArtifact=row_info["filename"],
                    sourceBinaryHash=inspected["binary_hash"],
                    sourceHash=hashlib.sha256(source.encode()).hexdigest(),
                    binaryHash=sha, filename=filename, compilerSha256=compiler))
            except (ValueError, LookupError, OSError, KeyError, TypeError) as exc:
                raise ValueError(f"NS[{row['slot']}] {name}: latest development compilation failed: {exc}. "
                                 "No older copy was substituted; nothing was sent.") from exc
        write_approvals(str(root / "approvals.json"), approvals)
        yield resolved, root, evidence
        if manifest_path.read_bytes() != manifest_bytes or compiler_fingerprint() != compiler:
            raise ValueError("Compilation inputs changed during preparation. Rebuild before sending; nothing was sent.")
