'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const {JSDOM} = require('jsdom');
(async () => {
 const dom = new JSDOM('<details id="editorSavedLumpPicker" open><div id="editorSavedLumpChoices"></div><p id="editorSavedLumpError" hidden></p></details>', {runScripts:'outside-only'});
 const w=dom.window;
 const source=fs.readFileSync(__dirname+'/app-lumps.js','utf8');
 w.eval(source.slice(0,source.indexOf('\n}',source.indexOf('async function refreshEditorSavedLumps'))+2));
 const row=(version,extra={})=>({abstraction:'Example',token:'12345678',filename:'Example.lump',binary_hash:'a'.repeat(64),lump_version:version,...extra});
 w.fetch=async()=>({ok:true,json:async()=>[row(1),row(2),row(3,{archived:true})]});
 let selected;
 w.openLumpInEditor=async(token,options)=>{selected={token,options};};
 await w.refreshEditorSavedLumps();
 const list=w.document.getElementById('editorSavedLumpChoices');
 assert.equal(list.children.length,1);
 assert.match(list.textContent,/v2/);
 await list.firstChild.onclick();
 assert.equal(selected.options.exactSavedArtifact.lump_version,2);
 assert.equal(selected.options.exactSavedArtifact.abstraction,'Example');
 assert.equal(w.document.getElementById('editorSavedLumpPicker').open,false);
 w.openLumpInEditor=async()=>{throw Error('Draft retained');};
 await list.firstChild.onclick();
 assert.match(w.document.getElementById('editorSavedLumpError').textContent,/Draft retained/);
 assert(!list.firstChild.disabled);
 w.fetch=async()=>({ok:false,status:503});
 await w.refreshEditorSavedLumps();
 assert.match(w.document.getElementById('editorSavedLumpError').textContent,/503/);
 dom.window.close();
 console.log('PASS saved-LUMP toolbar: latest choices, exact identity, guarded open, visible errors');
})().catch(e=>{console.error(e);process.exitCode=1;});
