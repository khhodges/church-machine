def test_save_ns_candidate_validation_and_config_write_failure_leave_all_files(
        client, tmp_path, monkeypatch):
    """Invalid candidates and final config-write failures publish no hybrid."""
    import server.app as app_module

    cfg = {**_cfg(), "targetBoard": "wukong-xc7a100t", "bootEntrySlot": 6}
    image = generate_boot_image(cfg, LUMPS_DIR, boot_entry_slot=6)
    config_path = tmp_path / "boot-config.json"
    image_path = tmp_path / "boot-image.bin"
    provenance_path = tmp_path / "boot-image.provenance.json"
    state_path = tmp_path / "ns-state.json"
    original = {
        config_path: b'{"old":"config"}',
        image_path: b"old-image",
        provenance_path: b'{"old":"provenance"}',
        state_path: b'{"abstractions":[],"committed_raw_fingerprint":"old"}',
    }
    for path, content in original.items():
        path.write_bytes(content)
    monkeypatch.setattr(app_module, "BOOT_CONFIG_PATH", str(config_path))
    monkeypatch.setattr(
        app_module, "BOOT_CONFIG_LEGACY_PATH", str(tmp_path / "no-legacy.json"))
    monkeypatch.setattr(app_module, "BOOT_IMAGE_PATH", str(image_path))
    monkeypatch.setattr(app_module, "BOOT_IMAGE_PROVENANCE_PATH", str(provenance_path))
    monkeypatch.setattr(app_module, "NS_STATE_PATH", str(state_path))
    payload = {
        "data_b64": base64.b64encode(image).decode("ascii"),
        "ns_state": {"abstractions": []},
        "boot_config": cfg,
    }

    invalid = dict(payload, boot_config={**cfg, "targetBoard": "not-a-board"})
    invalid_response = client.post("/api/boot-image/save-ns", json=invalid)
    assert invalid_response.status_code == 400
    assert all(path.read_bytes() == content for path, content in original.items())

    with patch.object(app_module, "_atomic_write_json",
                      side_effect=OSError("injected config write failure")):
        failed_response = client.post("/api/boot-image/save-ns", json=payload)
    assert failed_response.status_code == 500
    assert all(path.read_bytes() == content for path, content in original.items())