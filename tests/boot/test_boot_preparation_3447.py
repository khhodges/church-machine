def _cfg(thread_count=1):
    return {
        "step1": {
            "totalNamespaceWords": 16384,
            "namespaceLumpWords": 64,
            "threadLumpWords": 256,
            "threadCount": thread_count,
        },
    }


def _words(image):
    return list(struct.unpack(f"<{len(image) // 4}I", image))


def _thread_home_index(words):
    total = len(words)
    thread_loc = words[total - 2 * NS_ENTRY_WORDS]
    header = words[thread_loc]
    size = 1 << (((header >> 23) & 0xF) + 6)
    layout = thread_layout(size, (header >> 10) & 0x1FFF)
    assert layout["valid"]
    return thread_loc + layout["caps_start"]


def test_selected_target_sequence_is_serialized_in_layout_derived_cr0_home():
    image = generate_boot_image(_cfg(), LUMPS_DIR, boot_entry_slot=10)
    info = read_boot_entry_info(image)

    assert info["entry_slot"] == 10
    assert info["thread_caps_offset"] == 244
    assert info["thread_caps0"] == create_gt(
        info["entry_gt_seq"], 10, {"E": 1}, 1)
    assert info["caps0_ok"] is True


def test_reissued_selected_target_requires_matching_current_sequence_in_home():
    image = generate_boot_image(_cfg(), LUMPS_DIR, boot_entry_slot=10)
    words = _words(image)
    total = len(words)
    target_base = total - (10 + 1) * NS_ENTRY_WORDS
    sequence = 7
    words[target_base + 1] = (
        (words[target_base + 1] & ~(0x1FF << 21)) | (sequence << 21))
    words[target_base + 2] = integrity32(
        words[target_base], words[target_base + 1])
    current_gt = create_gt(sequence, 10, {"E": 1}, 1)
    thread_loc = words[total - 2 * NS_ENTRY_WORDS]
    header = words[thread_loc]
    layout = thread_layout(
        1 << (((header >> 23) & 0xF) + 6), (header >> 10) & 0x1FFF)
    words[thread_loc + layout["caps_start"]] = current_gt
    # The selected Boot.Thread continuation is part of the same prepared
    # primary context and must carry the destination descriptor's generation.
    words[thread_loc + layout["stack_end"] - 1] = current_gt
    reissued = struct.pack(f"<{total}I", *words)

    validate_boot_image(reissued)
    info = read_boot_entry_info(reissued)
    assert info["entry_gt_seq"] == sequence
    assert info["thread_caps0"] == create_gt(sequence, 10, {"E": 1}, 1)


